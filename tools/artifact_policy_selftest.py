def negative_r12_corpora() -> policy.Report:
    """The three ways a corpus declaration decays: unknown rule, dead path, dead row.

    The fourth shape — a corpus that suppresses the rule it declares — is the positive
    control, and it is asserted to leave `r12` silent.
    """
    report = policy.Report()
    live = policy.Corpus("tools/ledger_lint_corpus/", frozenset({"r2"}))
    stale_rule = policy.Corpus("tools/ledger_lint_corpus/", frozenset({"r99"}))
    absent = policy.Corpus("tools/no_such_corpus.py", frozenset({"r6"}))
    unused = policy.Corpus("tools/attestation_negative_corpus.py", frozenset({"r5"}))

    seeded = policy.Report()
    seeded.findings.append(
        policy.Finding("r2", "tools/ledger_lint_corpus/positive.json", "tracked JSON has the run-ledger shape")
    )
    policy.apply_corpora(seeded, [live])
    if seeded.findings:
        report.findings.append(
            policy.Finding("r12", "positive", "a declared corpus failed to suppress its own seed")
        )
    policy.audit_corpus_integrity(report, [live, stale_rule, absent, unused])
    return report


SYNTHETIC_TREE = """
```text
amoebius/
├── .gitignore                            authored worktree policy
├── DEVELOPMENT_PLAN/**                   authored plan suite
├── src/**                                authored Haskell library source
├── test/**                               authored specs, fixtures, goldens
├── .build/**                             every reproducible local output; ignored by both contracts
├── .data/**                              production runtime state; ignored by both contracts
└── .test_data/**                         harness-owned test state; ignored by both contracts
```

Two roots fix a second level:

```text
test/
├── fixture/**                            authored positive inputs
└── golden/**                             authored expected outputs
```
"""


def synthetic_tree() -> policy.TargetTree:
    """A four-root tree in the section-2 dialect, so the negatives never read doctrine.

    The parser is exercised against the real document by the audit itself; here the point
    is the membership decision, and a fixture tree makes each rejection reason explicit
    instead of implying it from whatever the repository happens to contain today.
    """
    return policy.parse_target_tree(policy.TREE_HEADING + SYNTHETIC_TREE + policy.TREE_STOP)


