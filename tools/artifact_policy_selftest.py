def run() -> bool:
    ok = True
    print(f"policy side — {len(NEGATIVES)} seeded negatives, one per rule\n")
    for rule, (name, build) in NEGATIVES.items():
        report = build()
        hit = _rules(report.findings)
        if not report.findings:
            print(f"  FAIL  {name:34s} {rule} stayed clean")
            ok = False
        elif hit != {rule}:
            print(f"  FAIL  {name:34s} expected only {rule}, got {', '.join(sorted(hit))}")
            ok = False
        else:
            print(f"  ok    {name:34s} {rule}  ({len(report.findings)} finding(s))")
    return ok


if __name__ == "__main__":
    raise SystemExit(0 if run() else 1)
